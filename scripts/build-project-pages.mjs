async function publicPages(directory) {
  const urls = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || ['src', 'static', 'scripts', 'node_modules'].includes(entry.name)) continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) urls.push(...await publicPages(path));
    else if (entry.name.endsWith('.html')) {
      const html = await readFile(path, 'utf8');
      if (/<meta[^>]+name="robots"[^>]+content="[^"]*noindex/i.test(html)) continue;
      const canonical = html.match(/<link rel="canonical" href="([^"]+)"/);
      if (!canonical) throw new Error(`Missing canonical: ${relative(root, path)}`);
      urls.push(canonical[1]);
    }
  }
  return urls;
}
const urls = [...new Set(await publicPages(root))].sort();
await output(resolve(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(url => `  <url><loc>${escape(url)}</loc></url>`).join('\n')}
</urlset>
`);
console.log(`${check ? 'Verified' : 'Generated'} ${Object.keys(PROJECTS).length} project pages and sitemap with ${urls.length} URLs.`);
