// Run after editing project data: node scripts/build-project-pages.mjs
// Commit the generated HTML: GitHub Pages serves these files without a build.
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { readFileSync } from 'node:fs';
import { resolve, dirname, relative } from 'node:path';
import { PROJECTS } from '../src/js/modules/projects.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const origin = 'https://ruckuslabs.co';
const check = process.argv.includes('--check');
async function output(path, content) {
  if (check) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Stale generated file: ${relative(root, path)}. Run node scripts/build-project-pages.mjs.`);
  } else {
    await writeFile(path, content);
  }
}

function imageSize(src) {
  const data = readFileSync(resolve(root, src.replace(/^\.?\//, '')));
  if (data.toString('ascii', 1, 4) === 'PNG') return [data.readUInt32BE(16), data.readUInt32BE(20)];
  if (data[0] === 0xff && data[1] === 0xd8) {
    let offset = 2;
    while (offset < data.length) {
      if (data[offset] !== 0xff) break;
      const marker = data[offset + 1];
      if ([0xc0, 0xc1, 0xc2, 0xc3, 0xc5, 0xc6, 0xc7, 0xc9, 0xca, 0xcb, 0xcd, 0xce, 0xcf].includes(marker)) {
        return [data.readUInt16BE(offset + 7), data.readUInt16BE(offset + 5)];
      }
      offset += 2 + data.readUInt16BE(offset + 2);
    }
  }
  const viewBox = data.toString('utf8').match(/viewBox=["']([\d.\s-]+)["']/);
  if (viewBox) return viewBox[1].trim().split(/\s+/).slice(2).map(Number);
  throw new Error(`Missing image dimensions: ${src}`);
}
const escape = value => String(value ?? '').replace(/[&<>"']/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[char]));
const asset = value => encodeURI('/' + value.replace(/^\.?\//, ''));

function image(src, alt, className = '', lazy = true) {
  const [width, height] = imageSize(src);
  return `<img width="${width}" height="${height}" src="${asset(src)}" alt="${escape(alt)}" class="${className}"${lazy ? ' loading="lazy"' : ''} decoding="async">`;
}

